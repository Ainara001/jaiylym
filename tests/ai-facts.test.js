// P2: проверка чисел в ответе ИИ и шаблонный ответ без Gemini (ai-facts.js).
const test = require("node:test");
const assert = require("node:assert/strict");
const F = require("../ai-facts.js");

const ctx = {
  село: "Кеген", хватает_ли_корма: "нет, не на весь сезон", поголовье_в_пересчёте_на_овец: 15384,
  ёмкость_всех_участков_с_водой_овец_за_сезон_оценка: 12040, модель_проверена_в_поле: false, демо_стада: true,
  причины_дефицита: [{ стадо: "Асан", причина: "capacity", не_хватает_дней: 23 }],
  узкое_место: { стада: ["Асан", "Бек"], не_хватает_усл_гол_сут: 4120 },
  что_можно_изменить: ["Водопой на Д-ЮВ откроет корм на 900 овец"],
  участки: [{ id: "Д-ЮВ", ndvi_спутник: 0.2893, ёмкость_овец_оценка: 367, как_рассчитано: "биомасса: (0.2893 - 0.10) × 4000 = 757 кг/га", маршрут: "Д-ЮВ д.1-30" }],
  итог: { перегружено_если_все_у_села: 4, перегружено_по_плану: 0, дефицит_сена_т_по_плану_оценка: 212, чтобы_корма_хватило_сократить_на_овец: 3344 },
};

test("числа из текста: разделители тысяч, запятая, диапазон дней", () => {
  assert.deepEqual(F.numbersIn("15 384 овец, NDVI 0,289, дни 1-30").map(n => n.v), [15384, 0.289, 1, 30]);
  assert.deepEqual(F.numbersIn("12 040").map(n => n.v), [12040]);
});

test("числа из данных проходят проверку, с округлением", () => {
  const r = F.verifyNumbers("На участке Д-ЮВ NDVI 0,29, ёмкость 367 овец, всего 15 384 овец; биомасса 757 кг/га; дефицит 212 т.", ctx);
  assert.equal(r.ok, true, r.unknown.join());
  assert.ok(r.checked >= 5);
});

test("выдуманное или посчитанное моделью число — незнакомое", () => {
  const r = F.verifyNumbers("Ёмкость 450 овец, доход вырастет на 35 %.", ctx);
  assert.equal(r.ok, false);
  assert.deepEqual(r.unknown, ["450", "35"]);
});

test("малые числа, годы и числа из вопроса пользователя не считаются выдуманными", () => {
  assert.equal(F.verifyNumbers("1) Главное. 2) В 2025 году так же.", ctx).ok, true);
  assert.equal(F.verifyNumbers("Для 500 овец места хватит.", ctx, "у меня 500 овец").ok, true);
});

test("шаблонный ответ: только числа из данных, на обоих языках", () => {
  for (const lang of ["ru", "kk"]) {
    const text = F.templateAnswer(ctx, lang, ["В расчёте есть условные демо-стада."], "");
    const r = F.verifyNumbers(text, ctx, "В расчёте есть условные демо-стада.");
    assert.equal(r.ok, true, lang + ": " + r.unknown.join());
    assert.match(text, /212/);
    assert.match(text, /Асан/);
  }
  assert.match(F.templateAnswer(ctx, "kk"), /жоқ, бүкіл маусымға жетпейді/);
});

test("шаблон без села — просит открыть село", () => {
  assert.match(F.templateAnswer({ село: null }, "ru", [], "серверы Google перегружены"), /перегружены[\s\S]*Село не открыто/);
});
